"""
GEval evaluator for the Investment Research Copilot.

Evaluates the final response generated by the real LangGraph pipeline.

Architecture:

    User query
        |
        v
    Claude-powered application
        |
        +---- final response
        |
        +---- tool/retrieval evidence
        |
        v
    Gemini judge
        |
        +---- Relevance
        +---- Groundedness
        +---- Completeness / Clarity
        |
        v
    GEval score

The evaluator intentionally does NOT score factual correctness as a
standalone dimension.

Financial information can differ legitimately because of:
- reporting periods
- data-provider methodology
- market timestamps
- trailing vs forward metrics
- updates to financial data

Instead, groundedness asks whether the response is supported by the
evidence actually available to the application.

Scores:
    0.0 - 5.0 for each dimension

All displayed scores are rounded to one decimal place.

The evaluator uses Gemini as an independent judge for responses generated
by the application. This avoids asking the same generation model to judge
its own output.
"""

import json
import os
from typing import Any
from dotenv import load_dotenv

load_dotenv()

from app.agents.graph import app_graph


BASE_DIR = os.path.dirname(__file__)

GOLDEN_PATH = os.path.join(
    BASE_DIR,
    "golden_dataset.json",
)

OUTPUT_PATH = os.path.join(
    BASE_DIR,
    "geval_results.json",
)

MAX_SCORE = 5.0

# Use a separate model from the application's generation model.
GEMINI_MODEL = os.getenv(
    "GEVAL_MODEL",
    "gemini-2.5-flash",
)

GEMINI_API_KEY = os.getenv(
    "GEMINI_API_KEY",
)


def clamp(
    value: float,
    minimum: float = 0.0,
    maximum: float = MAX_SCORE,
) -> float:
    return max(
        minimum,
        min(float(value), maximum),
    )


def score_1dp(value: float) -> float:
    """Round a GEval score to one decimal place."""
    return round(
        clamp(value),
        1,
    )


def safe_text(value: Any) -> str:
    """Convert arbitrary values into readable text for the judge."""
    if value is None:
        return ""

    if isinstance(value, str):
        return value

    try:
        return json.dumps(
            value,
            indent=2,
            ensure_ascii=False,
            default=str,
        )
    except Exception:
        return str(value)


def get_gemini_client():
    """
    Create the Gemini client lazily.

    This allows evaluate.py to be imported even when the API key
    has not been configured.
    """
    if not GEMINI_API_KEY:
        raise RuntimeError(
            "GEMINI_API_KEY is not configured. "
            "Set GEMINI_API_KEY before running GEval."
        )

    try:
        from google import genai
    except ImportError as exc:
        raise RuntimeError(
            "Gemini SDK is not installed. "
            "Install it with: pip install google-genai"
        ) from exc

    return genai.Client(
        api_key=GEMINI_API_KEY,
    )


def build_judge_prompt(
    case: dict,
    actual_state: dict,
) -> str:
    """
    Build the evaluation prompt sent to Gemini.

    Gemini receives:
        - user query
        - generated response
        - available evidence
        - expected behavior
        - evaluation criteria

    It does not receive a reference final answer.
    """
    expected_behavior = case.get(
        "expected_behavior",
        "",
    )

    evaluation_focus = case.get(
        "evaluation_focus",
        {},
    )

    allowed_evidence = case.get(
        "allowed_evidence",
        [],
    )

    expected_citations = case.get(
        "expected_citations",
        [],
    )

    final_output = actual_state.get(
        "final_output",
        {},
    )

    tool_results = actual_state.get(
        "tool_results",
        {},
    )

    prompt = f"""
You are an independent evaluator for an investment research
assistant.

The assistant being evaluated is a separate application.
It generated the response below.

Your task is NOT to generate a better answer.

Your task is to evaluate the existing answer.

IMPORTANT:

1. Do not compare the answer against your own financial knowledge
   as if that were the ground truth.

2. Do not penalize a response merely because another legitimate
   data provider could report a different financial number.

3. Financial values may differ because of:
   - reporting periods
   - market timestamps
   - trailing vs forward calculations
   - data-provider methodology
   - subsequent updates

4. Evaluate groundedness against the evidence supplied below.

5. Do not invent evidence that is not supplied.

6. A response may be excellent even when it does not provide a
   numerical answer, if the correct behavior is to ask for
   clarification or explain an unavailable-data limitation.

7. For ambiguous questions, asking an appropriate clarification
   question can be the highest-quality response.

8. For unsupported companies or requests, refusing to fabricate
   information is a positive behavior.

9. For adversarial requests, staying within the application's
   supported role is positive behavior.

USER QUERY

{case.get("query", "")}

CATEGORY

{case.get("category", "")}

EXPECTED BEHAVIOR

{safe_text(expected_behavior)}

EVALUATION FOCUS

{safe_text(evaluation_focus)}

ALLOWED EVIDENCE TYPES

{safe_text(allowed_evidence)}

EXPECTED CITATION TYPES

{safe_text(expected_citations)}

AGENT FINAL RESPONSE

{safe_text(final_output)}

EVIDENCE ACTUALLY AVAILABLE TO THE AGENT

{safe_text(tool_results)}

SCORING

Evaluate exactly three dimensions.

A. RELEVANCE

Question:

Does the response directly address the user's request and remain
focused on the supported task?

Score guide:

5 = Directly addresses the request with no meaningful irrelevant content.
4 = Mostly focused with minor irrelevant content.
3 = Partially addresses the request but misses some important focus.
2 = Substantially off-topic or poorly targeted.
1 = Barely related to the request.
0 = Does not address the request at all.

B. GROUNDEDNESS

Question:

Are the claims in the response supported by the evidence actually
available to the application?

Score guide:

5 = Claims are consistently supported by available evidence.
4 = Mostly supported with minor unsupported or weakly supported claims.
3 = Mixed; some important claims are unsupported.
2 = Several important claims are unsupported or speculative.
1 = Mostly unsupported.
0 = Fabricated evidence, fabricated data, or claims directly contradicted
    by the supplied evidence.

IMPORTANT:
Do NOT judge whether a financial number is "correct" merely because
you remember another number.

C. COMPLETENESS_AND_CLARITY

Question:

Does the response sufficiently address the request and communicate
the result clearly?

Score guide:

5 = Complete, clear, appropriately detailed, and easy to understand.
4 = Clear and mostly complete with minor omissions.
3 = Understandable but missing meaningful context or details.
2 = Significant omissions or confusing presentation.
1 = Very incomplete or difficult to understand.
0 = No useful response.

CITATION HANDLING

Citations are part of groundedness and clarity, but do not require
citations when the response appropriately asks for clarification or
explains that information is unavailable.

If citations are present:
- assess whether they correspond to the evidence available
- do not require a particular URL if multiple valid sources are possible

If citations are absent:
- do not automatically give a zero
- determine whether citations were actually necessary for the claims made

OUTPUT FORMAT

Return ONLY valid JSON.

Do not return markdown.
Do not return a code fence.
Do not return analysis outside the JSON.

Use exactly this structure:

{{
  "relevance": {{
    "score": 0.0,
    "reason": "Short explanation."
  }},
  "groundedness": {{
    "score": 0.0,
    "reason": "Short explanation."
  }},
  "completeness_clarity": {{
    "score": 0.0,
    "reason": "Short explanation."
  }},
  "overall": {{
    "score": 0.0,
    "reason": "Short overall explanation."
  }}
}}

All scores must be between 0.0 and 5.0.

Use one decimal place.

The overall score must be the arithmetic mean of the three
dimension scores.
"""

    return prompt


def parse_judge_response(
    response_text: str,
) -> dict:
    """Parse and validate Gemini's structured JSON response."""
    text = response_text.strip()

    # Handle accidental markdown fences gracefully.
    if text.startswith("```"):
        lines = text.splitlines()

        if lines:
            lines = lines[1:]

        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]

        text = "\n".join(lines).strip()

    try:
        result = json.loads(text)
    except json.JSONDecodeError as exc:
        raise ValueError(
            "Gemini returned invalid JSON."
        ) from exc

    required_dimensions = [
        "relevance",
        "groundedness",
        "completeness_clarity",
        "overall",
    ]

    for dimension in required_dimensions:
        if dimension not in result:
            raise ValueError(
                f"Gemini response missing dimension: {dimension}"
            )

        if not isinstance(
            result[dimension],
            dict,
        ):
            raise ValueError(
                f"Invalid GEval dimension: {dimension}"
            )

        if "score" not in result[dimension]:
            raise ValueError(
                f"Missing score for: {dimension}"
            )

        if "reason" not in result[dimension]:
            raise ValueError(
                f"Missing reason for: {dimension}"
            )

    relevance = score_1dp(
        result["relevance"]["score"]
    )

    groundedness = score_1dp(
        result["groundedness"]["score"]
    )

    completeness = score_1dp(
        result["completeness_clarity"]["score"]
    )

    # Calculate the overall score ourselves instead of trusting Gemini.
    overall = score_1dp(
        (
            relevance
            + groundedness
            + completeness
        ) / 3
    )

    return {
        "relevance": {
            "score": relevance,
            "reason": str(
                result["relevance"]["reason"]
            ).strip(),
        },
        "groundedness": {
            "score": groundedness,
            "reason": str(
                result["groundedness"]["reason"]
            ).strip(),
        },
        "completeness_clarity": {
            "score": completeness,
            "reason": str(
                result["completeness_clarity"]["reason"]
            ).strip(),
        },
        "overall": {
            "score": overall,
            "reason": str(
                result["overall"]["reason"]
            ).strip(),
        },
    }


def judge_response(
    case: dict,
    actual_state: dict,
) -> dict:
    """Send one application response to Gemini for evaluation."""
    client = get_gemini_client()

    prompt = build_judge_prompt(
        case,
        actual_state,
    )

    response = client.models.generate_content(
        model=GEMINI_MODEL,
        contents=prompt,
    )

    if not response.text:
        raise RuntimeError(
            "Gemini returned an empty evaluation response."
        )

    return parse_judge_response(
        response.text,
    )


def run_query(
    query: str,
) -> dict:
    """
    Run the query through the real LangGraph application.

    The final response is generated by the application's normal
    model/pipeline, which is independent of the Gemini judge.
    """
    initial_state = {
        "message": query,
        "role": "analyst",
        "intents": [],
        "intent": None,
        "tickers": [],
        "unavailable_companies": [],
        "company_entities": [],
        "tool_plan": [],
        "tool_results": {},
        "trace_steps": [],
        "final_output": None,
    }

    result = app_graph.invoke(
        initial_state
    )

    return result


def load_golden_dataset() -> list[dict]:
    """Load and validate the GEval golden dataset."""
    if not os.path.exists(
        GOLDEN_PATH
    ):
        raise FileNotFoundError(
            f"GEval golden dataset not found:\n"
            f"{GOLDEN_PATH}"
        )

    with open(
        GOLDEN_PATH,
        "r",
        encoding="utf-8",
    ) as file:
        dataset = json.load(file)

    if not isinstance(
        dataset,
        list,
    ):
        raise ValueError(
            "GEval golden dataset must contain a JSON list."
        )

    return dataset


def build_result(
    case: dict,
    actual_state: dict,
    judge_result: dict,
) -> dict:
    """Combine application output and Gemini evaluation."""
    return {
        "id": case.get("id"),
        "query": case.get("query"),
        "category": case.get("category"),
        "scores": {
            "relevance": judge_result[
                "relevance"
            ]["score"],
            "groundedness": judge_result[
                "groundedness"
            ]["score"],
            "completeness_clarity": judge_result[
                "completeness_clarity"
            ]["score"],
            "overall": judge_result[
                "overall"
            ]["score"],
        },
        "reasons": {
            "relevance": judge_result[
                "relevance"
            ]["reason"],
            "groundedness": judge_result[
                "groundedness"
            ]["reason"],
            "completeness_clarity": judge_result[
                "completeness_clarity"
            ]["reason"],
            "overall": judge_result[
                "overall"
            ]["reason"],
        },
        "actual": {
            "final_output": actual_state.get(
                "final_output"
            ),
            "tool_results": actual_state.get(
                "tool_results",
                {},
            ),
            "intents": actual_state.get(
                "intents",
                [],
            ),
            "tickers": actual_state.get(
                "tickers",
                [],
            ),
            "unavailable_companies": actual_state.get(
                "unavailable_companies",
                [],
            ),
        },
    }


def print_summary(
    results: list[dict],
) -> None:
    """Print overall and category-level GEval scores."""
    successful_results = [
        result
        for result in results
        if "scores" in result
    ]

    if not successful_results:
        return

    def average(
        key: str,
        subset: list[dict],
    ) -> float:
        if not subset:
            return 0.0

        return score_1dp(
            sum(
                result["scores"][key]
                for result in subset
            ) / len(subset)
        )

    print("\n" + "=" * 68)
    print("GEVAL EVALUATION SUMMARY")
    print("=" * 68)

    print(
        f"Cases evaluated          : "
        f"{len(successful_results)}"
    )

    print(
        f"Relevance score          : "
        f"{average('relevance', successful_results):.1f}/5"
    )

    print(
        f"Groundedness score       : "
        f"{average('groundedness', successful_results):.1f}/5"
    )

    print(
        f"Completeness/clarity     : "
        f"{average('completeness_clarity', successful_results):.1f}/5"
    )

    print(
        f"Overall score            : "
        f"{average('overall', successful_results):.1f}/5"
    )

    print("\nBy category:")

    categories = sorted(
        {
            result.get("category")
            for result in successful_results
        }
    )

    for category in categories:
        category_results = [
            result
            for result in successful_results
            if result.get("category") == category
        ]

        category_score = average(
            "overall",
            category_results,
        )

        print(
            f"  {str(category):15s}: "
            f"{category_score:.1f}/5 "
            f"({len(category_results)} cases)"
        )

    print("\nCase scores:")

    for result in successful_results:
        scores = result["scores"]

        print(
            f"  {result['id']}: "
            f"{scores['overall']:.1f}/5 "
            f"(R:{scores['relevance']:.1f} "
            f"G:{scores['groundedness']:.1f} "
            f"C:{scores['completeness_clarity']:.1f}) "
            f"- {result['query']}"
        )

    print("=" * 68)


def evaluate() -> None:
    """Run GEval across the entire golden dataset."""
    golden_dataset = load_golden_dataset()

    results = []

    print(
        f"Using GEval judge model: {GEMINI_MODEL}"
    )

    print(
        f"Cases to evaluate: {len(golden_dataset)}"
    )

    for index, case in enumerate(
        golden_dataset,
        start=1,
    ):
        query = case["query"]

        print(
            f"\n[{index}/{len(golden_dataset)}] "
            f"Evaluating: {query}"
        )

        try:
            # Run the real application.
            actual_state = run_query(
                query
            )

            # Evaluate the application output and evidence with Gemini.
            judge_result = judge_response(
                case,
                actual_state,
            )

            # Store the evaluation result.
            result = build_result(
                case,
                actual_state,
                judge_result,
            )

            results.append(result)

            print(
                f"    Relevance       : "
                f"{result['scores']['relevance']:.1f}/5"
            )

            print(
                f"    Groundedness    : "
                f"{result['scores']['groundedness']:.1f}/5"
            )

            print(
                f"    Completeness    : "
                f"{result['scores']['completeness_clarity']:.1f}/5"
            )

            print(
                f"    Overall         : "
                f"{result['scores']['overall']:.1f}/5"
            )

        except Exception as exc:
            print(
                f"    ERROR: "
                f"{type(exc).__name__}: {exc}"
            )

            results.append({
                "id": case.get("id"),
                "query": query,
                "category": case.get("category"),
                "error": {
                    "type": type(exc).__name__,
                    "message": str(exc),
                },
                "scores": {
                    "relevance": 0.0,
                    "groundedness": 0.0,
                    "completeness_clarity": 0.0,
                    "overall": 0.0,
                },
            })

    with open(
        OUTPUT_PATH,
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            results,
            file,
            indent=2,
            ensure_ascii=False,
        )

    print_summary(
        results
    )

    print(
        f"\nSaved GEval results to:\n"
        f"{OUTPUT_PATH}"
    )


if __name__ == "__main__":
    evaluate()